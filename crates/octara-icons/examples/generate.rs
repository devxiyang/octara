//! Generates `src/lucide.rs` from a lucide-static npm package:
//!
//! ```text
//! curl -sL https://registry.npmjs.org/lucide-static/-/lucide-static-<version>.tgz | tar xz
//! cargo run -p octara-icons --example generate -- package
//! ```
//!
//! Every icon (aliases left out) goes through `Icon::svg`, so the generated data is what the SVG
//! subset makes of it: path data on the 24-unit grid, each part stroked and / or filled.

use octara::icon::Icon;
use octara::path::{LineCap, LineJoin, PathStyle};
use std::fmt::Write;
use std::path::Path;

fn const_name(name: &str) -> String {
    let n = name.to_uppercase().replace('-', "_");
    if n.starts_with(|c: char| c.is_ascii_digit()) { format!("I{n}") } else { n }
}

fn main() {
    let dir = std::env::args().nth(1).expect("usage: generate <lucide-static package dir>");
    let dir = Path::new(&dir);
    let read = |p: &str| std::fs::read_to_string(dir.join(p)).unwrap_or_else(|e| panic!("{p}: {e}"));
    let package: serde_json::Value = serde_json::from_str(&read("package.json")).unwrap();
    let version = package["version"].as_str().unwrap();
    let nodes: serde_json::Value = serde_json::from_str(&read("icon-nodes.json")).unwrap();
    let tags: serde_json::Value = serde_json::from_str(&read("tags.json")).unwrap();
    let mut names: Vec<&str> = nodes.as_object().unwrap().keys().map(|k| k.as_str()).collect();
    names.sort();

    let mut out = String::new();
    writeln!(out, "// @generated by `cargo run -p octara-icons --example generate` from lucide-static {version}.").unwrap();
    writeln!(out, "// Do not edit. The icons are ISC licensed (some MIT, from Feather): see LICENSE-LUCIDE.\n").unwrap();
    writeln!(out, "use crate::Entry;\nuse octara::icon::{{Icon, IconPart}};\n").unwrap();
    writeln!(out, "/// The Lucide version the set was generated from.\npub const VERSION: &str = \"{version}\";\n").unwrap();
    let part = |d: &str, fill: bool, stroke: bool| format!("IconPart {{ data: {d:?}, fill: {fill}, stroke: {stroke} }}");
    let mut seen = std::collections::HashSet::new();
    for name in &names {
        let icon = Icon::svg(&read(&format!("icons/{name}.svg"))).unwrap_or_else(|e| panic!("{name}: {e}"));
        let b = icon.bounds();
        assert_eq!((b.x, b.y, b.w, b.h), (0.0, 0.0, 24.0, 24.0), "{name}: view box");
        let shapes = icon.shapes(None);
        let mut parts = Vec::new();
        let mut i = 0;
        while i < shapes.len() {
            let s = &shapes[i];
            let d = s.path.to_svg();
            match &s.style {
                PathStyle::Fill(_) => {
                    let stroked = shapes.get(i + 1).is_some_and(|n| n.path == s.path && matches!(n.style, PathStyle::Stroke(_)));
                    parts.push(part(&d, true, stroked));
                    i += if stroked { 2 } else { 1 };
                }
                PathStyle::Stroke(st) => {
                    assert!(st.width == 2.0 && st.cap == LineCap::Round && st.join == LineJoin::Round, "{name}: stroke {st:?}");
                    parts.push(part(&d, false, true));
                    i += 1;
                }
            }
        }
        let c = const_name(name);
        assert!(seen.insert(c.clone()), "{name}: duplicate constant {c}");
        writeln!(out, "/// Lucide `{name}`.\npub const {c}: Icon = Icon::stroked({name:?}, &[{}]);", parts.join(", ")).unwrap();
    }
    writeln!(out, "\n/// Every icon, by name (sorted), with its search tags.\npub static ALL: &[Entry] = &[").unwrap();
    for name in &names {
        let t: Vec<String> =
            tags[name].as_array().map(|a| a.iter().filter_map(|t| t.as_str()).map(|t| format!("{t:?}")).collect()).unwrap_or_default();
        writeln!(out, "    Entry {{ name: {name:?}, tags: &[{}], icon: {} }},", t.join(", "), const_name(name)).unwrap();
    }
    writeln!(out, "];").unwrap();
    let target = Path::new(env!("CARGO_MANIFEST_DIR")).join("src/lucide.rs");
    std::fs::write(&target, out).unwrap();
    eprintln!("wrote {} ({} icons, lucide-static {version})", target.display(), names.len());
}
